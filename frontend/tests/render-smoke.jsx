import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {Overview,Trends,Forecasts,Evaluation} from '../src/Pages.jsx';
import {SourceDialog} from '../src/Dialogs.jsx';
import {Stat,Table} from '../src/UI.jsx';
const study=JSON.parse(readFileSync('.browser-artifacts/study.json','utf8'));
const observations=study.observations,regions=Object.keys(study.regions),noop=()=>{};
function render(Component,props){const markup=renderToStaticMarkup(<Component {...props}/>);assert(!markup.includes('NaN'),'Rendering must not leak NaN into the interface');return markup;}
const common={study,observations,regions,onSources:noop,onNavigate:noop,onInspect:noop};
const stat=render(Stat,{label:'Countries',value:95,note:'Distinct reporting countries across the input period',icon:'people'});
assert(stat.includes('aria-describedby=')&&stat.includes('role="tooltip"'),'Metric values need accessible hover help');
assert(!stat.includes('<small>'),'Metric explanations should not occupy a permanent caption');
const helpedTable=render(Table,{columns:[{key:'score',label:'MAE',help:'Mean absolute error in percentage points'}],rows:[{score:9.61}]});
assert(helpedTable.includes('role="tooltip"')&&helpedTable.includes('Mean absolute error'));
assert.equal((helpedTable.match(/aria-describedby=/g)||[]).length,2,'Both the column and parameter value offer help');
const overview=render(Overview,{...common,year:2022,setYear:noop});
assert(overview.includes('70.6%')&&overview.includes('9.61'));
assert(!overview.includes('Simple can be powerful.')&&!overview.includes('Reporting-country counts vary. Every comparison needs that context.'));
assert(overview.includes('history eligibility')&&overview.includes('not the count for the selected year'));
const trends=render(Trends,{observations,regions,from:2016,to:2022,setFrom:noop,setTo:noop});
assert(trends.includes('11.22')&&trends.includes('2016'));
const forecast=render(Forecasts,{...common,region:'AFR',setRegion:noop,model:'ridge',setModel:noop});
assert(forecast.includes('76.28')&&forecast.includes('Experimental 2023 forecast'));
const sparse=render(Forecasts,{...common,region:'AMR',setRegion:noop,model:'ridge',setModel:noop});
assert(sparse.includes('Insufficient data to forecast'));
const evaluation=render(Evaluation,common);
assert(evaluation.includes('9.61')&&evaluation.includes('12.25')&&evaluation.includes('2022'));
assert(evaluation.includes('Root mean squared error')&&evaluation.includes('Mean absolute error'));
assert(evaluation.includes('<details class="method-details">')&&!evaluation.includes('<details class="method-details" open'),'Methodology is collapsed initially');
const provenance=render(SourceDialog,{study,onClose:noop,definition:'ECOLI_3GC_BSI|derived_country_median'});
assert(provenance.includes('412')&&provenance.includes('not independently authenticate'));
// Isolated regression scenarios; no synthetic observations enter the app data.
const officialRows=observations.map(r=>({...r,statistic_type:'who_unadjusted_regional_median'}));
const official=render(Overview,{...common,observations:officialRows,year:2022,setYear:noop});
assert(official.includes('WHO unadjusted regional median'));
assert(!official.includes('Observed · Derived reporting-country median'));
const otherStudy={...study,observations:[{...officialRows[0],year:2020},{...officialRows[0],year:2021}]};
const otherSource=render(SourceDialog,{study:otherStudy,onClose:noop,definition:'ECOLI_3GC_BSI|who_unadjusted_regional_median'});
assert(otherSource.includes('2020–2021'));
assert(!otherSource.includes('29 Oct 2026'));
const wrongTarget=render(Evaluation,{...common,observations:officialRows});
assert(!wrongTarget.includes('Reproducibility notes'));
const onlyNaive={...study,forecasts:study.forecasts.filter(r=>r.model==='naive')};
const fallback=render(Forecasts,{...common,study:onlyNaive,region:'AFR',setRegion:noop,model:'ridge',setModel:noop});
assert(fallback.includes('Experimental 2023 forecast: 70.63'));
const withMissing=[...observations,{...observations.find(r=>r.who_region==='AFR'),year:2025,resistance_pct:null}];
const missing=render(Overview,{...common,observations:withMissing,year:2025,setYear:noop});
assert(missing.includes('0 / 6'));
assert(!missing.includes('2016–2025'));
for(const [name,markup] of Object.entries({overview,trends,forecast,evaluation}))writeFileSync(`.browser-artifacts/${name}.html`,'<!doctype html><meta charset="utf-8"><link rel="stylesheet" href="../dist/assets/app.css">'+markup);
console.log('React render checks passed: four populated views, sparse forecasts, provenance, cross-target labels, null observations, and available-model fallback.');
